# ------------------------------------------------------------------ search and workspaces

def test_search_sql_ranks_exact_id_first(c):
    with SessionLocal() as db:
        rid = db.query(Research.id).filter(Research.status != "archived").first()[0]
    r = c.get("/api/search", params={"q": rid.lower()}).json()
    grp = next(g for g in r["groups"] if g["label"] == "Research")
    assert grp["items"][0]["id"] == rid
    # LIKE wildcards in user text are literal, not match-everything
    r = c.get("/api/search", params={"q": "%"}).json()
    assert all(g["label"] != "Research" for g in r["groups"])
    r = c.get("/api/search", params={"q": "toolshell"}).json()
    assert any(g["label"] == "Research" and g["items"] for g in r["groups"])
    assert len(next(g for g in r["groups"] if g["label"] == "Research")["items"]) <= 6


def test_workspace_counts_match_python(c):
    with SessionLocal() as db:
        rows = db.query(Research.workspace_ids).all()
    expect = {}
    for (ids,) in rows:
        for w in set(ids or []):
            expect[w] = expect.get(w, 0) + 1
    for w in c.get("/api/workspaces").json():
        assert w["research_count"] == expect.get(w["id"], 0)


def test_research_fts_tracks_inserts_updates_deletes(c):
    from app.migrate import research_fts_available
    with SessionLocal() as db:
        if not research_fts_available(db):
            pytest.skip("SQLite without FTS5 trigram")
        db.add(Research(id="TR-2098-0001", title="W1 fts probe", status="draft", search_text="w1 quokkaprobe marker"))
        db.commit()
    hit = lambda q: [i["id"] for g in c.get("/api/search", params={"q": q}).json()["groups"] if g["label"] == "Research" for i in g["items"]]  # noqa: E731
    try:
        assert hit("quokkaprobe") == ["TR-2098-0001"]
        assert hit("QUOKKA") == ["TR-2098-0001"]  # case-insensitive substring
        assert hit("tr-2098-0001") == ["TR-2098-0001"]  # id is indexed too
        with SessionLocal() as db:
            db.get(Research, "TR-2098-0001").search_text = "w1 wombatprobe marker"
            db.commit()
        assert hit("quokkaprobe") == [] and hit("wombatprobe") == ["TR-2098-0001"]
    finally:
        with SessionLocal() as db:
            db.delete(db.get(Research, "TR-2098-0001"))
            db.commit()
    assert hit("wombatprobe") == []
