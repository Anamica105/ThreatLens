def test_put_keys_encrypts_and_api_masks(c, secret_key, clean_keys):
    full = "vt-SECRET-abcdefghijkl-9876"
    assert c.put("/api/settings/osint-keys", json={"keys": {"virustotal": full}}, headers=HUNTER).status_code == 403
    r = c.put("/api/settings/osint-keys", json={"keys": {"virustotal": full, "bogus": "x"}}, headers=LEAD)
    assert r.status_code == 200
    assert full not in r.text and "SECRET" not in r.text
    vt = next(k for k in r.json() if k["id"] == "virustotal")
    assert vt["configured"] is True and vt["source"] == "settings" and vt["hint"] == "••••9876"
    got = c.get("/api/settings/osint-keys").json()
    assert full not in str(got)
    with SessionLocal() as db:
        stored = db.get(Setting, "osint_keys").value
        assert set(stored) == {"virustotal"} and stored["virustotal"].startswith("enc:v1:")
        # Readers (pipeline, library re-enrich) get the usable key through osint.get_keys.
        assert osint.get_keys(db)["virustotal"] == full
        assert secrets.get_secret("virustotal", db) == full
    r = c.put("/api/settings/osint-keys", json={"keys": {"virustotal": None}}, headers=LEAD)
    assert next(k for k in r.json() if k["id"] == "virustotal")["source"] != "settings"


