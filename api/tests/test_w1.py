def test_header_mode(c, monkeypatch):
    s = get_settings()
    monkeypatch.setattr(s, "auth_mode", "header")
    monkeypatch.setattr(s, "auth_trusted_proxies", "testclient,10.0.0.0/8")
    h = {"X-Forwarded-Email": "S.Kapoor@threatlens.local"}
    assert c.get("/api/me", headers=h).json()["id"] == "skapoor"
    # X-User is ignored in header mode
    assert c.get("/api/me", headers={**h, "X-User": "averma"}).json()["id"] == "skapoor"
    assert c.get("/api/me", headers=HUNTER).status_code == 401
    assert c.get("/api/me", headers={"X-Forwarded-Email": "stranger@example.com"}).status_code == 403
    monkeypatch.setattr(s, "auth_header", "X-Auth-Request-Email")
    assert c.get("/api/me", headers={"X-Auth-Request-Email": "a.verma@threatlens.local"}).json()["id"] == "averma"
    monkeypatch.setattr(s, "auth_trusted_proxies", "10.0.0.0/8")  # TestClient's peer is not a trusted proxy
    assert c.get("/api/me", headers={"X-Auth-Request-Email": "a.verma@threatlens.local"}).status_code == 401


