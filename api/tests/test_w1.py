def test_key_autogenerated_into_data_dir(monkeypatch, tmp_path, caplog):
    monkeypatch.setattr(get_settings(), "threatlens_secret_key", "")
    monkeypatch.delenv("THREATLENS_SECRET_KEY", raising=False)
    monkeypatch.setattr(get_settings(), "data_dir", tmp_path)
    secrets.reset()
    try:
        tok = secrets.encrypt("v")
        assert (tmp_path / ".secret_key").exists()
        assert "THREATLENS_SECRET_KEY is not set" in caplog.text
        secrets.reset()  # re-read from file: same key
        assert secrets.decrypt(tok) == "v"
    finally:
        secrets.reset()


