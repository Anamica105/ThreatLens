# ------------------------------------------------------------------ B14 secrets

def test_encrypt_roundtrip_and_mask(secret_key):
    tok = secrets.encrypt("abcdef1234567890")
    assert tok.startswith("enc:v1:") and "abcdef" not in tok
    assert secrets.decrypt(tok) == "abcdef1234567890"
    assert secrets.decrypt("legacy-plain") == "legacy-plain"
    assert secrets.mask("abcdef1234567890") == "••••7890"
    assert secrets.mask("short") == "••••"  # too short to reveal any characters
    assert secrets.mask("") == ""


