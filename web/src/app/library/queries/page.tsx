"use client";

import { Code } from "lucide-react";
import Link from "next/link";
import { useState } from "react";
import { CardLink, LibraryLayout, RailGroup } from "@/components/library";
import { useApp, useWsHref } from "@/components/providers";
import { highlight } from "@/components/research/syntax";
import { AttackChip, Badge, QueryStatusPill } from "@/components/ui/badges";
import { EmptyState, ErrorState, SkeletonRows } from "@/components/ui/feedback";
import { Page, PageHeader, Pagination } from "@/components/ui/layout";
import { qs } from "@/lib/api";
import { QUERY_STATUS, QUERY_TYPE } from "@/lib/constants";
import { relative, utc } from "@/lib/format";
import { useApi, useDebounced, useLocalStorage } from "@/lib/hooks";

interface Q { id: string; title: string; platform: string; type: string; body: string; techniques: string[]; status: string; origin: string; research_count: number; updated_at: string; deployed_workspaces: string[] }

export default function QueryLibrary() {
  const wsHref = useWsHref();
  const { meta, platformName } = useApp();
  const [q, setQ] = useState("");
  const dq = useDebounced(q);
  const [platform, setPlatform] = useState("");
  const [type, setType] = useState("");
  const [status, setStatus] = useState("");
  const [origin, setOrigin] = useState("");
  const [page, setPage] = useState(1);
  const [view, setView] = useLocalStorage<"cards" | "list">("tl.view.queries", "list");
  const { data, error, reload } = useApi<{ total: number; items: Q[] }>(`/api/library/queries${qs({ q: dq, platform, type, status, origin, page, page_size: 50 })}`);
  return (
    <Page>
      <PageHeader crumbs={[{ label: "Libraries" }, { label: "Detection queries" }]} title="Detection queries" description="Hunt and detection queries from every run, with the Sigma source they were translated from." />
      <LibraryLayout search={q} onSearch={(v) => { setQ(v); setPage(1); }} searchLabel="Search title, ID or query text" view={view} onView={setView}
        activeFilters={[platform, type, status, origin].filter(Boolean).length}
        filters={<>
          <div>
            <div className="mb-1.5 text-caption font-semibold text-fg-muted">Platform</div>
            <select className="h-7 w-full rounded-sm border border-line-strong bg-surface px-2 text-[13px]" value={platform} onChange={(e) => { setPlatform(e.target.value); setPage(1); }} aria-label="Platform">
              <option value="">Any platform</option>
              {(meta?.platforms ?? []).map((p) => <option key={p.id} value={p.id}>{p.name}</option>)}
            </select>
          </div>
          <RailGroup label="Type" options={Object.keys(QUERY_TYPE)} value={type} onChange={(v) => { setType(v); setPage(1); }} />
          <RailGroup label="Status" options={Object.keys(QUERY_STATUS)} value={status} onChange={(v) => { setStatus(v); setPage(1); }} />
          <RailGroup label="Origin" options={["generated", "reference"]} value={origin} onChange={(v) => { setOrigin(v); setPage(1); }} />
        </>}>
        {error ? <ErrorState error={error} onRetry={reload} /> : !data ? <SkeletonRows /> : !data.items.length ? (
          <EmptyState icon={<Code />} title="No queries match" body="Queries are generated by research runs for each selected platform." />
        ) : view === "cards" ? (
          <>
            <div className="grid gap-6 md:grid-cols-2 xl:grid-cols-3">
              {data.items.map((x) => (
                <CardLink key={x.id} href={wsHref(`/library/queries/${x.id}`)}>
                  <div className="flex items-start gap-2"><h3 className="line-clamp-2 flex-1 text-h4 font-semibold">{x.title}</h3></div>
                  <div className="flex flex-wrap gap-1.5"><Badge>{platformName(x.platform, true)}</Badge><Badge>{QUERY_TYPE[x.type] ?? x.type}</Badge></div>
                  <pre className="relative h-[66px] overflow-hidden rounded-sm bg-code px-2 py-1.5 font-mono text-mono-sm">
                    {highlight(x.body.split("\n").slice(0, 3).join("\n"), x.platform)}
                    <span className="absolute inset-x-0 bottom-0 h-6 bg-gradient-to-t from-[var(--bg-code)] to-transparent" />
                  </pre>
                  <div className="relative z-[1] flex flex-wrap gap-1">{x.techniques.slice(0, 2).map((t) => <AttackChip key={t} id={t} />)}</div>
                  <div className="mt-auto flex items-center gap-2 border-t border-line pt-3 text-caption text-fg-muted">
                    <QueryStatusPill status={x.status} /><span>Used in {x.research_count} research</span><span className="ml-auto" title={utc(x.updated_at)}>{relative(x.updated_at)}</span>
                  </div>
                </CardLink>
              ))}
            </div>
            <Pagination page={page} pageSize={50} total={data.total} onPage={setPage} />
          </>
        ) : (
          <div className="rounded-md border border-line bg-surface">
            <div className="overflow-x-auto">
              <table className="tl-table tl-compact w-full">
                <thead><tr><th>ID</th><th>Title</th><th>Platform</th><th>Type</th><th>Techniques</th><th>Status</th><th className="num">Research</th><th>Updated</th></tr></thead>
                <tbody>{data.items.map((x) => (
                  <tr key={x.id}>
                    <td><Link href={wsHref(`/library/queries/${x.id}`)} className="font-mono text-mono-sm text-accent-text hover:underline">{x.id}</Link></td>
                    <td className="max-w-[360px] truncate" title={x.title}>{x.title}</td>
                    <td className="whitespace-nowrap">{platformName(x.platform, true)}</td>
                    <td>{QUERY_TYPE[x.type] ?? x.type}</td>
                    <td className="font-mono text-mono-sm">{x.techniques.join(", ") || "—"}</td>
                    <td><QueryStatusPill status={x.status} /></td>
                    <td className="num">{x.research_count}</td>
                    <td className="whitespace-nowrap" title={utc(x.updated_at)}>{relative(x.updated_at)}</td>
                  </tr>
                ))}</tbody>
              </table>
            </div>
            <Pagination page={page} pageSize={50} total={data.total} onPage={setPage} />
          </div>
        )}
      </LibraryLayout>
    </Page>
  );
}
