"use client";

import { Code, SearchX } from "lucide-react";
import Link from "next/link";
import { useState } from "react";
import { ChipList } from "@/components/chip-list";
import { CardFooter, CardGrid, CardLink, LibraryEmpty, LibraryLayout, TableShell, single } from "@/components/library";
import { useApp, useWsHref } from "@/components/providers";
import { highlight } from "@/components/research/syntax";
import { AttackChip, Badge, QueryStatusPill } from "@/components/ui/badges";
import { Button } from "@/components/ui/button";
import { ErrorState, SkeletonRows } from "@/components/ui/feedback";
import { Page, PageHeader, Pagination } from "@/components/ui/layout";
import { qs } from "@/lib/api";
import { QUERY_STATUS, QUERY_TYPE } from "@/lib/constants";
import { relative, utc } from "@/lib/format";
import { useApi, useDebounced, useLocalStorage } from "@/lib/hooks";

interface Q { id: string; title: string; platform: string; type: string; body: string; techniques: string[]; status: string; origin: string; research_count: number; updated_at: string; deployed_workspaces: string[] }

export default function QueryLibrary() {
  const wsHref = useWsHref();
  const { meta, platformName } = useApp();
  const [q, setQ] = useState("");
  const dq = useDebounced(q);
  const [platform, setPlatform] = useState("");
  const [type, setType] = useState("");
  const [status, setStatus] = useState("");
  const [origin, setOrigin] = useState("");
  const [page, setPage] = useState(1);
  const [view, setView] = useLocalStorage<"cards" | "list">("tl.view.queries", "list");
  const { data, error, reload } = useApi<{ total: number; items: Q[] }>(`/api/library/queries${qs({ q: dq, platform, type, status, origin, page, page_size: 50 })}`);
  const reset = <T,>(set: (v: T) => void) => (v: T) => { set(v); setPage(1); };
  const filtered = !!(dq || platform || type || status || origin);
  const clear = () => { setQ(""); setPlatform(""); setType(""); setStatus(""); setOrigin(""); setPage(1); };
  return (
    <Page>
      <PageHeader crumbs={[{ label: "Libraries" }, { label: "Detection queries" }]} title="Detection queries" description="Hunt and detection queries from every run, with the Sigma source they were translated from." />
      <LibraryLayout storageKey="queries" search={q} onSearch={reset(setQ)} searchLabel="Search title, ID or query text" view={view} onView={setView}
        total={data?.total} noun={["query", "queries"]} onClearAll={clear}
        filters={[
          { key: "platform", label: "Platform", options: (meta?.platforms ?? []).map((p) => ({ value: p.id, label: p.name })), ...single(platform, reset(setPlatform)) },
          { key: "type", label: "Type", options: Object.entries(QUERY_TYPE).map(([value, label]) => ({ value, label })), ...single(type, reset(setType)) },
          { key: "status", label: "Status", options: Object.entries(QUERY_STATUS).map(([value, s]) => ({ value, label: s.label })), ...single(status, reset(setStatus)) },
          { key: "origin", label: "Origin", options: [{ value: "generated", label: "Generated" }, { value: "reference", label: "Reference" }], ...single(origin, reset(setOrigin)) },
        ]}>
        {error ? <ErrorState error={error} onRetry={reload} /> : !data ? <SkeletonRows /> : !data.items.length ? (
          filtered ? <LibraryEmpty icon={<SearchX />} title="No queries match" body="Try another search term or remove a filter." action={<Button onClick={clear}>Clear filters</Button>} />
            : <LibraryEmpty icon={<Code />} title="No queries yet" body="Queries are generated by research runs for each selected platform." />
        ) : view === "cards" ? (
          <>
            <CardGrid>
              {data.items.map((x) => (
                <CardLink key={x.id} href={wsHref(`/library/queries/${x.id}`)} label={x.title}>
                  <div className="min-w-0">
                    <div className="mb-0.5 font-mono text-mono-sm text-fg-muted">{x.id}</div>
                    <h3 className="line-clamp-2 text-h4 font-semibold break-words decoration-1 underline-offset-2 group-hover:underline" title={x.title}>{x.title}</h3>
                  </div>
                  <div className="flex min-w-0 flex-wrap gap-1.5"><Badge>{platformName(x.platform, true)}</Badge><Badge>{QUERY_TYPE[x.type] ?? x.type}</Badge></div>
                  <pre className="relative h-[66px] min-w-0 overflow-hidden rounded-sm bg-code px-2 py-1.5 font-mono text-mono-sm whitespace-pre">
                    {highlight(x.body.split("\n").slice(0, 3).join("\n"), x.platform)}
                    <span className="absolute inset-x-0 bottom-0 h-6 bg-gradient-to-t from-[var(--bg-code)] to-transparent" />
                  </pre>
                  {x.techniques.length > 0 && <div className="relative z-[1] flex min-w-0 flex-wrap gap-1">{x.techniques.slice(0, 2).map((t) => <AttackChip key={t} id={t} />)}{x.techniques.length > 2 && <span className="self-center text-caption text-fg-muted">+{x.techniques.length - 2}</span>}</div>}
                  <CardFooter>
                    <QueryStatusPill status={x.status} /><span className="min-w-0 truncate">Used in {x.research_count} research</span><span className="ml-auto shrink-0" title={utc(x.updated_at)}>{relative(x.updated_at)}</span>
                  </CardFooter>
                </CardLink>
              ))}
            </CardGrid>
            <Pagination page={page} pageSize={50} total={data.total} onPage={setPage} />
          </>
        ) : (
          <TableShell footer={<Pagination page={page} pageSize={50} total={data.total} onPage={setPage} />}>
            <table className="tl-table tl-compact w-full">
              <thead><tr><th>ID</th><th>Title</th><th>Platform</th><th>Type</th><th>Techniques</th><th>Status</th><th className="num">Research</th><th>Updated</th></tr></thead>
              <tbody>{data.items.map((x) => (
                <tr key={x.id}>
                  <td className="whitespace-nowrap"><Link href={wsHref(`/library/queries/${x.id}`)} className="font-mono text-mono-sm text-accent-text hover:underline">{x.id}</Link></td>
                  <td className="max-w-[360px] truncate" title={x.title}>{x.title}</td>
                  <td className="whitespace-nowrap">{platformName(x.platform, true)}</td>
                  <td className="whitespace-nowrap">{QUERY_TYPE[x.type] ?? x.type}</td>
                  <td><ChipList items={x.techniques} mono /></td>
                  <td><QueryStatusPill status={x.status} /></td>
                  <td className="num">{x.research_count}</td>
                  <td className="whitespace-nowrap" title={utc(x.updated_at)}>{relative(x.updated_at)}</td>
                </tr>
              ))}</tbody>
            </table>
          </TableShell>
        )}
      </LibraryLayout>
    </Page>
  );
}
